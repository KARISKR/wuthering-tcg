export function getCharacterOpeningQuote(charNameOrTitle?: string): string {
  if (!charNameOrTitle) return '공명을 시작합니다. 준비되셨나요?';
  const name = charNameOrTitle.trim();
  for (const [key, quote] of Object.entries(CHARACTER_OPENING_QUOTES)) {
    if (name.includes(key)) return quote;
  }
  return `${name}이(가) 당당히 전장에 출격했습니다!`;
}

